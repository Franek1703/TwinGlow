// ─── Accessors ───────────────────────────────────────────────────────────────

const uint8_t* digitBig(uint8_t digit) {
    if (digit > 9) return nullptr;
    return BIG_DIGITS[digit];
}

const uint8_t* glyph(char c) {
    if (c >= '0' && c <= '9') return SMALL_DIGITS[c - '0'];
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    if (c >= 'A' && c <= 'Z') return SMALL_LETTERS[c - 'A'];
    switch (c) {
        case '%': return SMALL_PERCENT;
        case '.': return SMALL_DOT;
        case '-': return SMALL_DASH;
        case ' ': return SMALL_SPACE;
        default:  return nullptr;
    }
}

uint8_t textWidth(const String& text) {
    if (text.length() == 0) return 0;
    return (uint8_t)(text.length() * GLYPH_ADVANCE - 1);
}

uint8_t digitsBigWidth(const String& digits) {
    if (digits.length() == 0) return 0;
    return (uint8_t)(digits.length() * DIGIT_BIG_ADVANCE - 1);
}

